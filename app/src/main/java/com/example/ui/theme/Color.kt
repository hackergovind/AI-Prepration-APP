fun colorSchemeFor(palette: AccentPalette, darkTheme: Boolean): ColorScheme {
    return when (palette) {
        AccentPalette.SKY_FROST -> if (darkTheme) SkyFrostDarkScheme else SkyFrostLightScheme
        AccentPalette.BLUE_VIOLET -> if (darkTheme) BlueVioletDarkScheme else BlueVioletLightScheme
        AccentPalette.TEAL_SLATE -> if (darkTheme) TealSlateDarkScheme else TealSlateLightScheme
        AccentPalette.INDIGO_AMBER -> if (darkTheme) IndigoAmberDarkScheme else IndigoAmberLightScheme
    }
}
